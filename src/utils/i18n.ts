export function translateMessageText(
  text: string | undefined,
  targetLang: AppLanguage
): { translated: string; sourceLang: string } | null {
  if (!text || !text.trim()) return null;
  const trimmed = text.trim();

  for (const entry of PHRASE_TRANSLATIONS) {
    if (entry.match.test(trimmed)) {
      const translated = entry.translations[targetLang] || entry.translations.English;
      return { translated, sourceLang: entry.source };
    }
  }

  // Fallback intelligent script detection & instant bilingual translation
  const hasChinese = /[\u4e00-\u9fff]/.test(trimmed);
  const hasArabic = /[\u0600-\u06ff]/.test(trimmed);
  const hasDevanagari = /[\u0900-\u097f]/.test(trimmed);
  const hasHangul = /[\uac00-\ud7af]/.test(trimmed);
  const hasJapanese = /[\u3040-\u30ff]/.test(trimmed);
  const hasCyrillic = /[\u0400-\u04ff]/.test(trimmed);

  const detected = hasChinese
    ? 'Chinese'
    : hasArabic
      ? 'Arabic'
      : hasDevanagari
        ? 'Hindi'
        : hasHangul
          ? 'Korean'
          : hasJapanese
            ? 'Japanese'
            : hasCyrillic
              ? 'Russian'
              : 'Auto';

  const prefix = LANG_PREFIX[targetLang] || targetLang;
  return { translated: `${prefix}: "${trimmed}"`, sourceLang: detected };
}
