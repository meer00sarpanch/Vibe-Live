export function formatCurrencyPrice(pricePkr: number, country: CountryInfo): string {
  if (country.code === 'PK') return `Rs. ${pricePkr.toLocaleString()}`;
  const converted = pricePkr * country.rateFromPkr;
  if (converted < 10) {
    return `${country.currencySymbol}${converted.toFixed(2)}`;
  }
  return `${country.currencySymbol}${Math.round(converted).toLocaleString()}`;
}

